package activity

import (
	"crypto/rand"
	"encoding/hex"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"sync"
	"time"
)

// NewID returns a random event id (used for synthetic events).
func NewID() string {
	b := make([]byte, 16)
	if _, err := rand.Read(b); err != nil {
		return time.Now().UTC().Format("20060102T150405.000000000")
	}
	return hex.EncodeToString(b)
}

const (
	maxEvents    = 3000
	trimEventsTo = 2000
)

// Event is a recorded registry event (manifest-level only; blob traffic
// is filtered out by the caller via IsManifestEvent).
type Event struct {
	ID         string    `json:"id"`
	Timestamp  time.Time `json:"timestamp"`
	Action     string    `json:"action"` // push | pull | delete | mount
	Repository string    `json:"repository"`
	Tag        string    `json:"tag,omitempty"`
	Digest     string    `json:"digest,omitempty"`
	MediaType  string    `json:"mediaType,omitempty"`
	UserAgent  string    `json:"userAgent,omitempty"`
	Addr       string    `json:"addr,omitempty"`
}

type repoStats struct {
	LastPush time.Time `json:"lastPush"`
	LastPull time.Time `json:"lastPull"`
	Pushes   int64     `json:"pushes"`
	Pulls    int64     `json:"pulls"`
}

// Store keeps the recent event feed and per-repository push/pull stats,
// persisted as JSONL + JSON files in the data directory.
type Store struct {
	mu     sync.Mutex
	dir    string
	events []Event // newest first
	stats  map[string]*repoStats
	ids    map[string]bool
}

func New(dir string) *Store {
	_ = os.MkdirAll(dir, 0o700)
	return &Store{dir: dir, stats: map[string]*repoStats{}, ids: map[string]bool{}}
}

// Load restores stats and recent events from disk (called at startup).
func (s *Store) Load() error {
	s.mu.Lock()
	defer s.mu.Unlock()

	if data, err := os.ReadFile(filepath.Join(s.dir, "activity-stats.json")); err == nil {
		var st map[string]*repoStats
		if json.Unmarshal(data, &st) == nil {
			s.stats = st
		}
	}
	data, err := os.ReadFile(filepath.Join(s.dir, "events.jsonl"))
	if err != nil {
		return nil // no history yet
	}
	var events []Event
	for _, line := range strings.Split(string(data), "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		var ev Event
		if json.Unmarshal([]byte(line), &ev) == nil {
			events = append(events, ev)
		}
	}
	// the file is oldest-first; memory is newest-first
	for i := len(events) - 1; i >= 0; i-- {
		s.events = append(s.events, events[i])
		s.ids[events[i].ID] = true
	}
	return nil
}

// IsManifestEvent reports whether an event target refers to a manifest or
// an index (manifest media types contain "manifest" or "index"). Blob
// upload/download traffic (application/octet-stream) is excluded.
func IsManifestEvent(mediaType string) bool {
	return strings.Contains(mediaType, "manifest") || strings.Contains(mediaType, "index")
}

// Add records events and persists them. Events generated by our own
// backend (Go-http-client user agent) are skipped so that UI browsing does
// not pollute pull statistics. Returns the number of recorded events.
func (s *Store) Add(events []Event) int {
	s.mu.Lock()
	defer s.mu.Unlock()

	added := 0
	for _, ev := range events {
		if ev.ID == "" || s.ids[ev.ID] {
			continue
		}
		if strings.HasPrefix(ev.UserAgent, "Go-http-client") {
			continue
		}
		if ev.Timestamp.IsZero() {
			ev.Timestamp = time.Now()
		}
		s.ids[ev.ID] = true
		s.events = append([]Event{ev}, s.events...)
		added++

		st, ok := s.stats[ev.Repository]
		if !ok {
			st = &repoStats{}
			s.stats[ev.Repository] = st
		}
		switch ev.Action {
		case "push":
			st.Pushes++
			if ev.Timestamp.After(st.LastPush) {
				st.LastPush = ev.Timestamp
			}
		case "pull":
			st.Pulls++
			if ev.Timestamp.After(st.LastPull) {
				st.LastPull = ev.Timestamp
			}
		}
	}
	if added > 0 {
		s.persistLocked()
	}
	return added
}

// List returns up to n newest events, optionally filtered by repository.
func (s *Store) List(n int, repo string) []Event {
	s.mu.Lock()
	defer s.mu.Unlock()
	out := make([]Event, 0, n)
	for _, ev := range s.events {
		if repo != "" && ev.Repository != repo {
			continue
		}
		out = append(out, ev)
		if len(out) >= n {
			break
		}
	}
	return out
}

// StatsFor returns the push/pull statistics of one repository.
func (s *Store) StatsFor(repo string) (lastPush, lastPull time.Time, pushes, pulls int64, ok bool) {
	s.mu.Lock()
	defer s.mu.Unlock()
	st, found := s.stats[repo]
	if !found {
		return time.Time{}, time.Time{}, 0, 0, false
	}
	return st.LastPush, st.LastPull, st.Pushes, st.Pulls, true
}

func (s *Store) persistLocked() {
	if len(s.events) > maxEvents {
		s.events = s.events[:trimEventsTo]
		s.ids = map[string]bool{}
		for _, ev := range s.events {
			s.ids[ev.ID] = true
		}
	}

	var sb strings.Builder
	for i := len(s.events) - 1; i >= 0; i-- { // write oldest-first
		b, err := json.Marshal(s.events[i])
		if err != nil {
			continue
		}
		sb.Write(b)
		sb.WriteByte('\n')
	}
	writeFileAtomic(filepath.Join(s.dir, "events.jsonl"), []byte(sb.String()))

	if data, err := json.MarshalIndent(s.stats, "", "  "); err == nil {
		writeFileAtomic(filepath.Join(s.dir, "activity-stats.json"), data)
	}
}

func writeFileAtomic(path string, data []byte) {
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, data, 0o600); err != nil {
		return
	}
	_ = os.Rename(tmp, path)
}
